// The generated TypeScript types of the wire shapes, and the checks
// that hold them.
//
// The exporter renders every declaration, in a fixed order, into one text:
// a header naming the crate and its version, `JsonValue` (the exporter's
// own: an `OwnedDataValue` is datavalue's type, which cannot implement
// ts-rs's trait), then each wire shape's ts-rs `decl()`, derived or written
// by hand. The rendering changes only the layout and the rustdoc links in
// the comments, which a test holds. The text is `bindings/dataflow.d.ts`,
// committed, which 7d's wasm package embeds: a drift test compares the two,
// and `DATAFLOW_TS_WRITE=1` rewrites the file.
//
// The wire check reads serialized JSON, never the declarations' text: every
// corpus case v4 builds, run traced, and a set of runs made to write every
// optional key (a fan-out in a loop, timings, a removal, a replaced root,
// every run status, selection and exit), give messages, traces and runs;
// the corpus's definitions give issues. Each value is checked against its
// declaration, parsed from the rendered text by a small reader of the
// TypeScript the exporter writes: every key it writes is a declared property,
// every required property is present, and every value has its property's
// type. So a `skip_serializing_if` declared as required fails, as does a
// renamed key or a number declared as a string. Then every declared property
// and every literal of a declared union must have been written by some
// sample, so a key the serializers never write fails too.

use dataflow_rs::RunOptions;
use dataflow_rs::observe::{StepResult, Trace, TraceOptions, TraceStep};
use dataflow_rs::program::{AuthoredPath, IssueCode, Severity, StepKind, TaskIx, WorkflowIx};
use dataflow_rs::run::{
    AuditEntry, CancelToken, Change, Context, ErrorRecord, RunStatus, Selection, WorkflowExit,
    WorkflowRecord,
};
use dataflow_rs::{Ctx, Engine, Error, Function, Issue, Message, Outcome, Result, Run};
use datavalue::OwnedDataValue;
use serde::Serialize;
use serde_json::{Value, json};
use std::time::{Duration, Instant};
use ts_rs::{Config, TS};

#[path = "it/support/corpus_driver.rs"]
