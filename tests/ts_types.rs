/// The committed declarations.
const BINDINGS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/bindings/dataflow.d.ts");

/// The command that rewrites [`BINDINGS`], run at the repository's root.
fn regenerate() -> String {
    "DATAFLOW_TS_WRITE=1 cargo test --features ts --test ts_types".to_owned()
}

/// ts-rs's config: a 64-bit integer is a JSON number on this wire, not a
/// `bigint`. `Config::new`, not `from_env`, so no environment changes the
/// text.
fn config() -> Config {
    Config::new().with_large_int("number")
}

/// `JsonValue`, declared once, rendered as the exporter renders the rest.
const JSON_VALUE: &str = "\
/**
 * Any JSON value: a payload, a context root, and the values a change holds.
 */
export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };
";

/// Every wire shape's docs and ts-rs declaration, in the file's order.
fn declarations() -> Vec<(String, String)> {
    let cfg = config();
    macro_rules! decls {
        ($($ty:ty),* $(,)?) => {
            vec![$((<$ty as TS>::docs().unwrap_or_default(), <$ty as TS>::decl(&cfg))),*]
        };
    }
    decls![
        Message,
        Context,
        AuditEntry,
        Change,
        ErrorRecord,
        Trace,
        TraceStep,
        StepResult,
        WorkflowIx,
        TaskIx,
        Run,
        RunStatus,
        WorkflowRecord<'static>,
        Selection,
        WorkflowExit,
        Error,
        Issue,
        IssueCode,
        Severity,
        StepKind,
        AuthoredPath,
    ]
}

/// The whole file: the header, `JsonValue`, then every declaration.
fn render() -> String {
    let mut out = format!(
        "\
// The wire shapes of {name} {version} as TypeScript: what a message, its
// context, a run, a trace and an issue serialize as. Generated by
// `{file}` from the crate's types; do not edit. To regenerate:
//
//     {cmd}

{JSON_VALUE}",
        name = env!("CARGO_PKG_NAME"),
        version = dataflow_rs::VERSION,
        // With `/` on every platform, so the header is one text.
        file = file!().replace('\\', "/"),
        cmd = regenerate(),
    );
    for (docs, decl) in declarations() {
        out.push('\n');
        out.push_str(&tsd::render(&docs, &decl));
    }
    out
}

#[test]
fn the_committed_bindings_are_current() {
    let text = render();
    if std::env::var_os("DATAFLOW_TS_WRITE").is_some_and(|v| v == "1") {
        std::fs::create_dir_all(std::path::Path::new(BINDINGS).parent().unwrap()).unwrap();
        std::fs::write(BINDINGS, &text).unwrap();
        return;
    }
    // A checkout that turns line ends into `\r\n` (Git's `core.autocrlf` on
    // Windows) changes nothing the file says.
    let committed = std::fs::read_to_string(BINDINGS)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    if committed != text {
        let (line, (want, have)) = text
            .lines()
            .chain(std::iter::repeat(""))
            .zip(committed.lines().chain(std::iter::repeat("")))
            .enumerate()
            .find(|(_, (want, have))| want != have)
            .unwrap_or((0, ("", "")));
        panic!(
            "{BINDINGS} does not match the types it is generated from: line {} is\n    \
             {have:?}\nwhere the types give\n    {want:?}\nRegenerate it with\n\n    \
             {}\n\nand commit the result.",
            line + 1,
            regenerate()
        );
    }
}

#[test]
fn the_bindings_are_self_contained() {
    let text = render();
    assert!(
        !text.contains("import "),
        "no imports: 7d embeds the file whole"
    );
    let decls = tsd::parse(&text).unwrap_or_else(|e| panic!("the rendered text reads: {e}"));
    let names: Vec<&str> = decls.iter().map(|d| d.name.as_str()).collect();
    for (i, name) in names.iter().enumerate() {
        assert!(!names[..i].contains(name), "`{name}` is declared twice");
    }
    assert_eq!(names.iter().filter(|n| **n == "JsonValue").count(), 1);
    assert!(
        decls.iter().all(|d| d.exported),
        "every declaration is exported"
    );
    for d in &decls {
        for name in d.ty.references() {
            assert!(
                names.contains(&name),
                "`{}` names `{name}`, undeclared",
                d.name
            );
        }
    }
    // The global `Error` is not shadowed: `dataflow_rs::Error`'s JSON is
    // `DataflowError`.
    assert!(!names.contains(&"Error") && names.contains(&"DataflowError"));
}

#[test]
fn rendering_changes_only_the_layout_and_the_doc_links() {
    for (docs, decl) in declarations() {
        let raw = tsd::parse(&format!("{docs}{decl}")).unwrap_or_else(|e| panic!("{decl}: {e}"));
        let rendered = tsd::render(&docs, &decl);
        let back = tsd::parse(&rendered).unwrap_or_else(|e| panic!("{rendered}: {e}"));
        assert_eq!(raw.len(), 1);
        assert_eq!(raw, back, "{rendered}");
        assert_eq!(tsd::render(&docs, &decl), rendered);
    }
    assert_eq!(
        tsd::plain(" [`initial`](Self::initial), [`Path::set`], [a b](x::y()) and `v[i]`"),
        " `initial`, `Path::set`, a b and `v[i]`"
    );
}

